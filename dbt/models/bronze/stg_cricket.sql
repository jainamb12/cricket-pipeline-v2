with raw_cricket as (
    select * from {{ source('raw', 'CRICKET') }}
)

select
    TRIM(DELIVERY_ID) AS DELIVERY_ID,
    CAST(DELIVERY_TIMESTAMP AS TIMESTAMP) AS DELIVERY_TIMESTAMP,
    CAST(INNING_NO AS INTEGER) AS INNING_NO,
    CAST(OVER_NO AS INTEGER) AS OVER_NO,
    CAST(BALL_IN_OVER AS INTEGER) AS BALL_IN_OVER,
    CAST(RUNS_OFF_BAT AS INTEGER) AS RUNS_OFF_BAT,
    LOWER(TRIM(EXTRA_TYPE)) AS EXTRA_TYPE,
    CAST(EXTRA_RUNS AS INTEGER) AS EXTRA_RUNS,
    CAST(TOTAL_RUNS AS INTEGER) AS TOTAL_RUNS,
    CAST(IS_WICKET AS BOOLEAN) AS IS_WICKET,
    LOWER(TRIM(DISMISSAL_TYPE)) AS DISMISSAL_TYPE,
    CAST(BALL_SPEED_KMPH AS NUMERIC(10,2)) AS BALL_SPEED_KMPH,
    TRIM(NON_STRIKER_ID) AS NON_STRIKER_ID,
    LOWER(TRIM(SHOT_TYPE)) AS SHOT_TYPE,
    LOWER(TRIM(SHOT_REGION)) AS SHOT_REGION,
    TRIM(MATCH_ID) AS MATCH_ID,
    CAST(MATCH_DATE AS DATE) AS MATCH_DATE,
    UPPER(TRIM(MATCH_FORMAT)) AS MATCH_FORMAT,
    LOWER(TRIM(TOURNAMENT_NAME)) AS TOURNAMENT_NAME,
    CAST(SEASON AS INTEGER) AS SEASON,
    LOWER(TRIM(MATCH_STAGE)) AS MATCH_STAGE,
    LOWER(TRIM(TOSS_DECISION)) AS TOSS_DECISION,
    TRIM(VENUE_ID) AS VENUE_ID,
    LOWER(TRIM(VENUE_NAME)) AS VENUE_NAME,
    LOWER(TRIM(VENUE_CITY)) AS VENUE_CITY,
    LOWER(TRIM(VENUE_COUNTRY)) AS VENUE_COUNTRY,
    TRIM(BATTING_TEAM_ID) AS BATTING_TEAM_ID,
    LOWER(TRIM(BATTING_TEAM_NAME)) AS BATTING_TEAM_NAME,
    TRIM(BOWLING_TEAM_ID) AS BOWLING_TEAM_ID,
    LOWER(TRIM(BOWLING_TEAM_NAME)) AS BOWLING_TEAM_NAME,
    BATSMAN_ID,
    LOWER(TRIM(BATSMAN_NAME)) AS BATSMAN_NAME,
    CAST(TRIM(BATSMAN_DOB) AS DATE) AS BATSMAN_DOB,
    LOWER(TRIM(BATSMAN_NATIONALITY)) AS BATSMAN_NATIONALITY,
    LOWER(TRIM(BATTING_HAND)) AS BATTING_HAND,
    LOWER(TRIM(BATSMAN_ROLE)) AS BATSMAN_ROLE,
    TRIM(BATSMAN_EMAIL) AS BATSMAN_EMAIL,
    CASE
        WHEN BATSMAN_EMAIL LIKE '*@*.*' THEN BATSMAN_EMAIL
        ELSE NULL
    END AS BATSMAN_EMAIL
    TRIM(BATSMAN_PHONE) AS BATSMAN_PHONE,
    CAST(BATSMAN_ICC_RATING AS INTEGER) AS BATSMAN_ICC_RATING,
    TRIM(BOWLER_ID) AS BOWLER_ID,
    LOWER(TRIM(BOWLER_NAME)) AS BOWLER_NAME,
    LOWER(TRIM(BOWLER_NATIONALITY)) AS BOWLER_NATIONALITY,
    LOWER(TRIM(BOWLING_STYLE)) AS BOWLING_STYLE,
    CAST(BOWLER_ICC_RATING AS INTEGER) AS BOWLER_ICC_RATING,
    TRIM(CONTRACT_ID) AS CONTRACT_ID,
    LOWER(TRIM(CONTRACT_GRADE)) AS CONTRACT_GRADE,
    CAST(ANNUAL_RETAINER_USD AS NUMERIC(10,2)) AS ANNUAL_RETAINER_USD,
    LOWER(TRIM(CONTRACT_STATUS)) AS CONTRACT_STATUS,
    TRIM(DRS_REVIEW_ID) AS DRS_REVIEW_ID,
    LOWER(TRIM(DRS_REVIEWED_BY)) AS DRS_REVIEWED_BY,
    LOWER(TRIM(DRS_ORIGINAL_DECISION)) AS DRS_ORIGINAL_DECISION,
    LOWER(TRIM(DRS_OUTCOME)) AS DRS_OUTCOME,
    _file_name,
    coalesce(_loaded_at, current_timestamp()) as _ingested_at
from raw_cricket